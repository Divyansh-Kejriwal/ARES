USE CASES;
CREATE TABLE Case_info (CaseID INT PRIMARY KEY AUTO_INCREMENT, 
YOSARID VARCHAR(10) NOT NULL,
Latitude DECIMAL(10,8) NOT NULL,
Longitude DECIMAL(11,8) NOT NULL,
ContactMethod VARCHAR(100),
EnvRegion VARCHAR(100) NOT NULL,
EnvRegionCode VARCHAR(100) NOT NULL,
IncidentType VARCHAR(50) NOT NULL,
GroupDynamics VARCHAR(50) NOT NULL,
SubjectCategory VARCHAR(100) NOT NULL,
Subsex VARCHAR(3) NOT NULL,
SubAge INT);